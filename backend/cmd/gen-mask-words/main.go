// Command gen-mask-words generates the two word lists the masker reads
// (internal/threadctx/mask.go) from vendored sources, so no hand-written list
// decides which words are common or which are names:
//
//   - internal/threadctx/common_words.txt: the most frequent English words,
//     from the Wiktionary frequency lists of television and movie scripts as
//     zxcvbn-go ships them, kept when Webster's Second International lists
//     the word or a regular inflection of it in lower case, or when the word
//     is a contraction;
//   - internal/threadctx/names.txt: the en_US first and last names of
//     FakerPHP/Faker.
//
// Each output file states its sources, their licenses and the command that
// regenerates it in its own header. Run it with cwd=backend:
//
//	go mod download -json github.com/ccojocar/zxcvbn-go@v1.0.4   # prints Dir
//	curl -sSfLo /tmp/Person.php https://raw.githubusercontent.com/FakerPHP/Faker/v1.24.1/src/Faker/Provider/en_US/Person.php
//	go run ./cmd/gen-mask-words -english <Dir>/data/data/English.json -web2 /usr/share/dict/web2 -faker /tmp/Person.php
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"regexp"
	"slices"
	"strings"
)

const (
	commonPath = "internal/threadctx/common_words.txt"
	namesPath  = "internal/threadctx/names.txt"
	// commonCount is how many of the most frequent words are candidates.
	commonCount = 10000
)

const regenerate = `# Regenerate (cwd backend):
#   go mod download -json github.com/ccojocar/zxcvbn-go@v1.0.4   # prints Dir
#   curl -sSfLo /tmp/Person.php https://raw.githubusercontent.com/FakerPHP/Faker/v1.24.1/src/Faker/Provider/en_US/Person.php
#   go run ./cmd/gen-mask-words -english <Dir>/data/data/English.json -web2 /usr/share/dict/web2 -faker /tmp/Person.php
`

var commonHeader = fmt.Sprintf(`# Code generated by cmd/gen-mask-words. DO NOT EDIT.
#
# The common English words the masker keeps (internal/threadctx/mask.go): the
# %d most frequent words of the Wiktionary frequency lists of English as used
# in television and movie scripts, each kept when Webster's Second
# International Dictionary lists it, or the word an -s, -es, -ed, -d or -ing
# ending inflects, in lower case, or when it is a contraction whose last part
# is at most two letters or such a word. A word ending in 's is left out: the
# masker keeps that suffix apart from the word before it.
#
# Sources and licenses:
#   - Wiktionary, "Frequency lists: TV and movie scripts" (2006), CC BY-SA 3.0,
#     by the Wiktionary contributors; as data/data/English.json of
#     github.com/ccojocar/zxcvbn-go v1.0.4 (MIT). This list is a derivative of
#     it and is shared under CC BY-SA 3.0.
#   - Webster's Second International Dictionary (1934), public domain (its
#     copyright has lapsed), as share/dict/web2 of FreeBSD and macOS.
#
%s
`, commonCount, regenerate)

var namesHeader = `# Code generated by cmd/gen-mask-words. DO NOT EDIT.
#
# The names the masker treats as names (internal/threadctx/mask.go): a
# capitalized common word that is one of these is masked as a name. Every
# en_US first name (male and female) and last name, lower-cased.
#
# Source and license:
#   - FakerPHP/Faker v1.24.1, src/Faker/Provider/en_US/Person.php, MIT.
#
` + regenerate + "\n"

func main() {
	english := flag.String("english", "", "zxcvbn-go v1.0.4 data/data/English.json")
	web2 := flag.String("web2", "", "Webster's Second International word list (share/dict/web2)")
	faker := flag.String("faker", "", "FakerPHP/Faker v1.24.1 src/Faker/Provider/en_US/Person.php")
	flag.Parse()
	if err := run(*english, *web2, *faker); err != nil {
		fmt.Fprintf(os.Stderr, "gen-mask-words: %v\n", err)
		os.Exit(1)
	}
}

func run(englishPath, web2Path, fakerPath string) error {
	if englishPath == "" || web2Path == "" || fakerPath == "" {
		return fmt.Errorf("-english, -web2 and -faker are all required")
	}
	frequent, err := readEnglish(englishPath)
	if err != nil {
		return err
	}
	dictionary, err := readLowerWords(web2Path)
	if err != nil {
		return err
	}
	names, err := readFakerNames(fakerPath)
	if err != nil {
		return err
	}
	var common []string
	for _, w := range frequent[:min(commonCount, len(frequent))] {
		if isCommon(w, dictionary) {
			common = append(common, w)
		}
	}
	if err := write(commonPath, commonHeader, common); err != nil {
		return err
	}
	return write(namesPath, namesHeader, names)
}

func readEnglish(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var list struct{ List []string }
	if err := json.Unmarshal(raw, &list); err != nil {
		return nil, fmt.Errorf("decode %s: %w", path, err)
	}
	return list.List, nil
}

// readLowerWords returns the words of a one-word-per-line list that are
// written in lower case.
func readLowerWords(path string) (map[string]bool, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	out := map[string]bool{}
	for w := range strings.FieldsSeq(string(raw)) {
		if w == strings.ToLower(w) {
			out[w] = true
		}
	}
	return out, nil
}

var (
	fakerArray  = regexp.MustCompile(`(?s)protected static \$(firstNameMale|firstNameFemale|lastName) = \[(.*?)\];`)
	fakerString = regexp.MustCompile(`'((?:[^'\\]|\\.)+)'`)
)

// readFakerNames returns Faker's en_US first and last names, lower-cased,
// sorted and unique.
func readFakerNames(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	arrays := fakerArray.FindAllStringSubmatch(string(raw), -1)
	if len(arrays) != 3 {
		return nil, fmt.Errorf("%s: want the arrays firstNameMale, firstNameFemale and lastName, found %d", path, len(arrays))
	}
	var out []string
	for _, array := range arrays {
		for _, m := range fakerString.FindAllStringSubmatch(array[2], -1) {
			out = append(out, strings.ToLower(strings.ReplaceAll(m[1], `\'`, "'")))
		}
	}
	slices.Sort(out)
	return slices.Compact(out), nil
}

// isCommon reports whether a frequent word is kept as a common word.
func isCommon(w string, dictionary map[string]bool) bool {
	if strings.HasSuffix(w, "'s") {
		return false
	}
	if i := strings.LastIndex(w, "'"); i >= 0 {
		last := w[i+1:]
		return len(last) <= 2 || dictionary[last]
	}
	return dictionary[w] || inflects(w, dictionary)
}

// inflects reports whether w is a regular inflection of a dictionary word:
// an -s, -es, -ed, -d or -ing ending, a final y changed to i before -es or
// -ed, a final e dropped before -ing or -ed, or a final consonant doubled.
func inflects(w string, dictionary map[string]bool) bool {
	for _, e := range []struct{ suffix, restore string }{
		{"ies", "y"}, {"ied", "y"}, {"es", ""}, {"s", ""}, {"ed", ""}, {"ed", "e"}, {"d", ""}, {"ing", ""}, {"ing", "e"},
	} {
		stem, ok := strings.CutSuffix(w, e.suffix)
		if !ok || len(stem) < 2 {
			continue
		}
		if dictionary[stem+e.restore] {
			return true
		}
		if (e.suffix == "ed" || e.suffix == "ing") && len(stem) > 2 && stem[len(stem)-1] == stem[len(stem)-2] && dictionary[stem[:len(stem)-1]] {
			return true
		}
	}
	return false
}

func write(path, header string, words []string) error {
	words = slices.Clone(words)
	slices.Sort(words)
	words = slices.Compact(words)
	return os.WriteFile(path, []byte(header+strings.Join(words, "\n")+"\n"), 0o644)
}
