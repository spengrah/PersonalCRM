// Command gen-contact-queries generates the ListContacts/CountContacts/
// ListContactIDs query triple from the shared WHERE/ORDER BY fragment at
// internal/db/querygen/contact_list.sql.tmpl into the committed
// internal/db/queries/contact_list.gen.sql.
//
// Run via `make contact-queries` (writes the committed path) or
// `make contact-queries-check` (writes to a temp path and diffs). Both
// targets run this binary with cwd=backend, so the template and default
// output paths below are relative to that.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"text/template"
)

const (
	templatePath      = "internal/db/querygen/contact_list.sql.tmpl"
	rootTemplateName  = "contact_list.sql.tmpl"
	defaultOutputPath = "internal/db/queries/contact_list.gen.sql"
)

const header = `-- Code generated by cmd/gen-contact-queries. DO NOT EDIT.
-- Source: internal/db/querygen/contact_list.sql.tmpl
-- Regenerate with ` + "`make contact-queries`" + `; CI fails on drift.

`

func main() {
	out := flag.String("o", defaultOutputPath, "output path for the generated SQL file")
	flag.Parse()

	tmpl, err := template.ParseFiles(templatePath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-contact-queries: parse template: %v\n", err)
		os.Exit(1)
	}

	var body bytes.Buffer
	if err := tmpl.ExecuteTemplate(&body, rootTemplateName, nil); err != nil {
		fmt.Fprintf(os.Stderr, "gen-contact-queries: execute template: %v\n", err)
		os.Exit(1)
	}

	var full bytes.Buffer
	full.WriteString(header)
	full.Write(body.Bytes())

	if err := os.WriteFile(*out, full.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gen-contact-queries: write output: %v\n", err)
		os.Exit(1)
	}
}
